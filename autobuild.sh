cwd="$(pwd)"
cd "$(dirname "$0")"
cwd2="$(pwd)/.."
cd "$cwd"
LF="
"
os="$(uname -s)"
save="0"

random_func() {
	if [ "$os" = "FreeBSD" ]; then
		echo "$(jot -r 1 0 65535)"
	elif [ "$os" = "OpenBSD" ] || [ "$os" = "Haiku" ] || [ "$os" = "NetBSD" ]; then
		echo "$(od -An -N2 -tu2 /dev/urandom)"
	elif [ "$os" = "Linux" ]; then
		echo "$RANDOM"
	elif [ "$os" = "SunOS" ]; then
		set "$(/usr/xpg4/bin/od -A n -N 2 -t u1 /dev/urandom)"
		echo "$(($1 * 256 + $2))"
	else
		seed=$(($seed + 100)); awk -v seed=$seed 'BEGIN { srand(seed); print int(rand() * 65536) }'
	fi
}

TOK="__$(random_func)$(random_func)$(random_func)$(random_func)__"

eval "${TOK}MS_COMPILER=\"cc\""
eval "${TOK}MS_COMPILER_OUTPUT_FILE_PREFIX=\"-o \""
eval "${TOK}COMMANDLINE=\"-lm\""
eval "${TOK}COMPILERPREFIX=\"\""
eval "${TOK}INPUTMARK=\"\""
eval "${TOK}COMPILERINPUT=\"\""
eval "${TOK}COMPILEROUTPUT=\"\""
eval "${TOK}MS_TEMP=\"temp\""
eval "${TOK}MS_BIN=\"bin\""
eval "${TOK}PREFSLOADED=\"N\""
eval "${TOK}MIDDLEARGS=\"\""
eval "${TOK}MS_OS=\"\$os\""
eval "${TOK}MS_CD=\"\$cwd\""
eval "${TOK}MS_RESOURCE_COMPILER=\"windres\""
eval "${TOK}MS_FIRST_RESOURCE_ARGS=\"\""
eval "${TOK}MS_MIDDLE_RESOURCE_ARGS=\"\""
eval "${TOK}MS_LAST_RESOURCE_ARGS=\"\""
eval "${TOK}MS_RESOURCE_INPUT_FILE=\"resources64.rc\""
eval "${TOK}MS_RESOURCE_OUTPUT_FILE=\"\""
eval "${TOK}MS_RESOURCE_INPUT_FILE_PREFIX=\"\""
eval "${TOK}MS_RESOURCE_OUTPUT_FILE_PREFIX=\"\""
eval "${TOK}MS_RESOURCE_EXTENSION=\"opc\""
eval "${TOK}MS_BITS=\"64\""
eval "${TOK}MS_ARCH=\"$(uname -m)\""
SAVE_NAME="Autobuild.save.sh"
PREFS="$cwd/$SAVE_NAME"
COMMANDS=""
eval "${TOK}MS_SAVE=\"FALSE\""
eval "${TOK}MS_ERROR=\"FALSE\""

eval "${TOK}MS_ECHO=\"echo\""
eval "${TOK}MS_SPACE=\" \""
eval "${TOK}MS_NEW_LINE=$LF"
autodetect=""
CONFIGFILE="$cwd/Autobuild"
GENERATED_MESSAGE="Generated by Autobuild v1.0.0"

COMMAND_NEW_LINE="$LF		"

SAVE_FOUND="1"

case $PREFS in
	*/*)
		if [ ! -f "$PREFS" ]; then
			SAVE_FOUND="0"
		elif [ ! -x "$PREFS" ]; then
			SAVE_FOUND="0"
		fi
		;;
	*)
		if ! command -v "$PREFS" > /dev/null 2>&1; then
			SAVE_FOUND="0"
		fi
		;;
esac

if [ "$SAVE_FOUND" = "0" ]; then
	line="0"
	column="0"
	condition="0"
	ends="0"
	lastlabel="undefined"
	last_was_if="0"
	first_function_bracket="0"
	print_string=""
	USAGE_MESSAGE="{"
	while read -r p || [ -n "$p" ]; do
		line=$(($line + 1))
		column="0"
		opcode=""
		operand1=""
		sign=""
		operand2=""
		forward=""
		prefix=""
		operand3=""
		getvar=""
		getmsg=""
		first_function_bracket="0"
		print_string=""
		#echo $line: c: $condition, e: $ends
		for word in $p
		do
			if [ "$forward" != "" ]; then
				break
			fi
			column=$(($column + 1))
			if [ "$opcode" = "COMMAND" ]; then
				if [ "$condition" = "0" ]; then
					LC_ALL=C; export LC_ALL
					case "$word" in
						''|*[!A-Za-z0-9_]*)
							echo "[ERROR]: Invalid sub-command at line $line."
							;;
						*)
							eval "if [ \"\$${TOK}MS_$word\" != \"\" ]; then COMMANDS=\"\${COMMANDS}\$${TOK}MS_$word\"; export COMMANDS; elif [ \"\$${TOK}MS_$word\" != \"\" ]; then COMMANDS=\"\${COMMANDS}\$${TOK}MS_$word\"; export COMMANDS; fi"
							;;
					esac

				fi
			elif [ "$opcode" = "PRINT" ]; then
				if [ "$condition" = "0" ]; then
					if [ "$column" = "1" ]; then
						print_string="$word"
					else
						print_string="$print_string$word "
					fi
				fi
			elif [ "$opcode" = "MODE" ] || [ "$opcode" = "MODES" ]; then
				case "$word" in
						''|*[!A-Za-z0-9_]*)
							echo "[ERROR]: Invalid mode label at line $line."
							;;
						*)
							if [ "$USAGE_MESSAGE" = "{" ]; then
								USAGE_MESSAGE="$USAGE_MESSAGE$word"
							else
								USAGE_MESSAGE="$USAGE_MESSAGE|$word"
							fi
							if [ "$opcode" = "MODE" ]; then
								COMMANDS="$COMMANDS${LF}		${TOK}EMPTY_LOOP${TOK}=\"0\"${LF}	elif [ \"\$1\" = \"$word\" ]; then"
								forward="1"
							else
								if [ "$first_function_bracket" = "0" ]; then
									COMMANDS="$COMMANDS${LF}		${TOK}EMPTY_LOOP${TOK}=\"0\"${LF}	elif [ \"\$1\" = \"$word\" ]"
									first_function_bracket="1"
								else
									COMMANDS="$COMMANDS || [ \"\$1\" = \"$word\" ]"
								fi
							fi
							;;
				esac
			else
				if [ "$column" = "1" ]; then
					opcode="$word"
					if [ "$condition" = "0" ]; then
						if [ "$opcode" = "COMMAND" ]; then
							COMMANDS="${COMMANDS}$COMMAND_NEW_LINE"
						fi
					fi
					if [ "$opcode" = "END" ]; then
						if [ "$condition" != "0" ] ; then
							condition=$(($condition - 1))
						fi
						if [ "$ends" != "0" ] && [ "$last_was_if" != "1" ]; then
							ends=$(($ends - 1))
						fi
					fi
				elif [ "$column" = "2" ]; then
					operand1="$word"
				elif [ "$column" = "3" ]; then
					if [ "$opcode" = "VAR" ] || [ "$opcode" = "IF" ] || [ "$opcode" = "ELSEIF" ]; then
						sign="$word"
						prefix="${TOK}MS_"
					else
						operand2="$word"
					fi
				else
					if [ "$opcode" = "GET" ]; then
						prefix="${TOK}MS_"
						if [ "$operand3" = "" ]; then
							operand3="$word"
						else
							operand3="$operand3 $word"
						fi
					else
						if [ "$operand2" = "" ]; then
							operand2="$word"
						else
							operand2="$operand2 $word"
						fi
					fi
				fi
			fi
		done
		if [ "$first_function_bracket" = "1" ]; then
			COMMANDS="$COMMANDS; then"
		fi
		if [ "$print_string" != "" ]; then
			printf "$print_string\n"
		fi
		if [ "$forward" = "" ]; then
			if [ "$opcode" = "VAR" ] || [ "$opcode" = "IF" ] || [ "$opcode" = "ELSEIF" ] || [ "$opcode" = "SET" ] || [ "$opcode" = "SUBCOMMAND" ] || [ "$opcode" = "GET" ] || [ "$opcode" = "ELSE" ]; then
				if [ "$opcode" = "ELSE" ]; then
					if [ "$condition" = "1" ] && [ "$ends" = "0" ]; then
						last_was_if="1"
						condition=$(($condition - 1))
					elif [ "$condition" = "0" ]; then
						ends=$(($ends + 1));
						condition=$(($condition + 1))
						last_was_if="0"
					fi
				else
					LC_ALL=C; export LC_ALL
					case "$operand1" in
						''|*[!A-Za-z0-9_]*)
							echo "[ERROR]: Invalid variable at line $line."
							;;
						*)
							if [ "$opcode" = "IF" ] && [ "$condition" != "0" ]; then
								last_was_if="1"
								condition=$(($condition + 1))
							elif [ "$opcode" = "IF" ] && [ "$condition" == "0" ]; then
								last_was_if="1"
								if [ "$sign" = "=" ]; then
									eval "if [ \"\$$prefix$operand1\" != \"\$operand2\" ]; then condition=\$((\$condition + 1)); fi"
								elif [ "$sign" = "~=" ]; then
									eval "if [ \"\$$prefix$operand1\" = \"\$operand2\" ]; then condition=\$((\$condition + 1)); fi"
								else
									eval "if [ \"\$$prefix$operand1\" = \"\" ]; then condition=\$((\$condition + 1)); fi"
								fi
								lastlabel="$operand1"
							elif [ "$opcode" = "ELSEIF" ]; then
								if [ "$condition" = "1" ] && [ "$ends" = "0" ]; then
									if [ "$sign" = "=" ]; then
										eval "if [ \"\$$prefix$operand1\" = \"\$operand2\" ]; then condition=\$((\$condition - 1)); fi"
									elif [ "$sign" = "~=" ]; then
										eval "if [ \"\$$prefix$operand1\" != \"\$operand2\" ]; then condition=\$((\$condition - 1)); fi"
									else
										eval "if [ \"\$$prefix$operand1\" != \"\" ]; then condition=\$((\$condition - 1)); fi"
									fi
									if [ "$condition" = "0" ]; then
										last_was_if="1"
									fi
								elif [ "$condition" == "0" ]; then
									ends=$(($ends + 1));
									condition=$(($condition + 1))
									last_was_if="0"
								fi
							elif [ "$condition" == "0" ]; then
								if [ "$opcode" = "VAR" ]; then
									if [ "$opcode" != "VAR" ] || [ "$sign" = "=" ]; then
										eval "$prefix$operand1=\"\$operand2\"; export $prefix$operand1"
									fi
								elif [ "$opcode" = "GET" ] || [ "$opcode" = "SET" ]; then
									if [ "$operand1" = "INPUT" ]; then
										printf "$operand3"
										read "$prefix$operand2" < /dev/tty
									elif [ "$operand1" = "ENV" ]; then
										case "$operand2" in
											''|*[!A-Za-z0-9_]*)
												echo "[ERROR]: Invalid variable at line $line."
												;;
											*)
												case "$operand3" in
													''|*[!A-Za-z0-9_]*)
														echo "[ERROR]: Invalid environment variable at line $line."
														;;
													*)
														if [ "$operand1" = "ENV" ]; then
															if [ "$opcode" = "GET" ]; then
																eval "${TOK}MS_$operand3=\"\$$operand2\""
															elif [ "$opcode" = "SET" ]; then
																eval "$operand2=\"\$${TOK}MS_$operand3\""
															fi
														fi
														;;
												esac
												;;
										esac
									fi
								fi
							fi
							;;
					esac
				fi
			fi
		fi
		if [ "$forward" = "2" ]; then
			$forward = "0"
			break
		fi
	done < "$CONFIGFILE"
	USAGE_MESSAGE="$USAGE_MESSAGE}"
	echo "#!/usr/bin/env sh
#$GENERATED_MESSAGE
${TOK}EMPTY_LOOP${TOK}=\"1\"
${TOK}main${TOK}() {
	if [ \"\$1\" = \"build\" ]; then$COMMANDS
		${TOK}EMPTY_LOOP${TOK}=\"0\"
	fi
}
if [ \"\$#\" -eq 0 ]; then
	${TOK}main${TOK} \"build\"
else
	for arg in \"\$@\"
	do
		${TOK}main${TOK} \"\$arg\"
	done
fi
if [ \"\$${TOK}EMPTY_LOOP${TOK}\" = \"1\" ]; then
	echo \"Usage: \$0: $USAGE_MESSAGE\"
fi
" > "$PREFS"
	chmod +x "$PREFS"
	"$PREFS" "$@" && if [ "$(eval "echo \"\$${TOK}MS_SAVE\"")" != "TRUE" ]; then "$PREFS" "delete"; fi
else
	"$PREFS" "$@"
fi
